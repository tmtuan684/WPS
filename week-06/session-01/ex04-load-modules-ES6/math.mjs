export function add(a, b) {
    return Number(a) + Number(b);
}
export function substract(a, b) {
    return Number(a) - Number(b);
}
function multiple(a, b) {
    return Number(a) * Number(b);
}
function divide(a, b) {
    return Number(a) / Number(b);
}
